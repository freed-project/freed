#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const begin = "  // BEGIN GENERATED FACEBOOK ADMISSION POLICY";
const end = "  // END GENERATED FACEBOOK ADMISSION POLICY";
const policyPath = path.join(root, "packages/shared/src/provider-admission.ts");
const collectorPath = path.join(
  root,
  "packages/desktop/src-tauri/src/facebook-admission-collector.source.js",
);
const generatedPath = path.join(
  root,
  "packages/desktop/src-tauri/src/facebook-admission-policy.generated.js",
);
const extractorPaths = [
  path.join(root, "packages/desktop/src-tauri/src/fb-extract.js"),
  path.join(root, "packages/desktop/src-tauri/src/fb-stories-extract.js"),
];

const transpiled = ts.transpileModule(readFileSync(policyPath, "utf8"), {
  compilerOptions: {
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2019,
    removeComments: true,
  },
}).outputText
  .replace(/^export\s+/gm, "")
  .replace(/^export \{\};\s*$/gm, "")
  .trim();
const collector = readFileSync(collectorPath, "utf8").trim();
const generated = [
  "/* Generated by scripts/generate-provider-admission-policy.mjs. */",
  "var facebookAdmissionPolicy = (function () {",
  transpiled,
  "  return {",
  "    ruleVersion: PROVIDER_ADMISSION_RULE_VERSION,",
  "    decide: decideProviderPlacementAdmission,",
  "    validate: isProviderAdmissionEnvelope,",
  "  };",
  "})();",
  collector,
]
  .join("\n")
  .replace(/[ \t]+$/gm, "");
const block = `${begin}\n${generated
  .split("\n")
  .map((line) => (line ? `  ${line}` : ""))
  .join("\n")}\n${end}`;

function updateExtractor(filePath) {
  const source = readFileSync(filePath, "utf8");
  const start = source.indexOf(begin);
  const finish = source.indexOf(end);
  if (start < 0 || finish < start) {
    throw new Error(`Missing generated admission markers in ${path.relative(root, filePath)}`);
  }
  const next = source.slice(0, start) + block + source.slice(finish + end.length);
  if (check && next !== source) {
    throw new Error(`Generated admission policy is stale in ${path.relative(root, filePath)}`);
  }
  if (!check && next !== source) writeFileSync(filePath, next);
}

const currentGenerated = (() => {
  try {
    return readFileSync(generatedPath, "utf8");
  } catch {
    return null;
  }
})();
if (check && currentGenerated !== `${generated}\n`) {
  throw new Error("Generated Facebook admission asset is stale");
}
if (!check && currentGenerated !== `${generated}\n`) {
  writeFileSync(generatedPath, `${generated}\n`);
}
for (const extractorPath of extractorPaths) updateExtractor(extractorPath);
